#!/usr/bin/env python3
"""Build the primer library.

    python3 primer/lib/build.py            write what is stale
    python3 primer/lib/build.py --check    write no files, exit 1 if something is stale
    python3 primer/lib/build.py --snippets list the snippets and the pages that use them (writes no files)

What it does, in order:
  1. Joins lib/css/*.css (filename order) into assets/kit.css.
  2. Copies lib/kit.js to assets/kit.js.
  3. Builds every index.html from the page.html beside it, lib/template.html (lib/template-index.html for
     primer/page.html), the partials in lib/partials, the library table lib/libs.json and chapters.json.
     A {{snippet:key}} in a page.html becomes the text of lib/snippets/key.html. An unknown key is a problem and a
     snippet that no page uses is a warning. See lib/pages.py. A folder that has an index.html but no page.html is a problem.
  4. Stamps all local stylesheet and script references in the pages with ?v=<first 8 hex of the
     sha1 of that file's content>: assets/kit.css, assets/kit.js, the chapter's own <slug>.js and
     <slug>.css, and any other local .js or .css file beside a page. External URLs are left alone.
  5. Checks the rule "no <style> element in a page": a page may carry the library link, the chapter's own <slug>.css, the
     KaTeX and Google Fonts links, and nothing else that styles it. A <style> element or another stylesheet is a problem.

A second run finds nothing to change. Standard library only.
"""
import argparse
import glob
import hashlib
import os
import re
import sys
from urllib.parse import urlsplit

LIB = os.path.dirname(os.path.abspath(__file__))
PRIMER = os.path.dirname(LIB)
sys.dont_write_bytecode = True  # keep __pycache__ out of the repo
sys.path.insert(0, LIB)
import pages  # noqa: E402

CSS_DIR = os.path.join(LIB, "css")
KIT_JS_SRC = os.path.join(LIB, "kit.js")
KIT_CSS_OUT = os.path.join(PRIMER, "assets", "kit.css")
KIT_JS_OUT = os.path.join(PRIMER, "assets", "kit.js")

CSS_HEADER = "/* Generated by lib/build.py from lib/css. Do not edit. */\n"
JS_HEADER = "// Generated by lib/build.py from lib/kit.js. Do not edit.\n"

TAG = re.compile(r"<(link|script)\b([^>]*)>", re.I)
ATTR = re.compile(r"""\b(href|src)(\s*=\s*)(["'])([^"']*)\3""", re.I)


def read_bytes(path):
    with open(path, "rb") as f:
        return f.read()


def read_text(path):
    return read_bytes(path).decode("utf-8")


def short_hash(data):
    return hashlib.sha1(data).hexdigest()[:8]


def build_css():
    files = sorted(glob.glob(os.path.join(CSS_DIR, "*.css")))
    if not files:
        raise SystemExit("no css files in " + CSS_DIR)
    parts = []
    for path in files:
        text = read_text(path)
        if not text.endswith("\n"):
            text += "\n"
        parts.append(text)
    return CSS_HEADER + "\n".join(parts), [os.path.basename(p) for p in files]


def build_js():
    text = read_text(KIT_JS_SRC)
    if not text.endswith("\n"):
        text += "\n"
    return JS_HEADER + text


def page_sources():
    """Return (page.html paths, problems). primer/page.html is the front page; each folder has its own."""
    sources, problems = [], []
    top = os.path.join(PRIMER, "page.html")
    if os.path.isfile(top):
        sources.append(top)
    elif os.path.isfile(os.path.join(PRIMER, "index.html")):
        problems.append("index.html: no page.html beside it (the front page is generated from primer/page.html)")
    for folder in sorted(glob.glob(os.path.join(PRIMER, "*", ""))):
        name = os.path.basename(os.path.normpath(folder))
        src = os.path.join(folder, "page.html")
        if os.path.isfile(src):
            sources.append(src)
        elif os.path.isfile(os.path.join(folder, "index.html")):
            problems.append("%s/index.html: no page.html beside it (a page is generated from its page.html; see lib/README.md)" % name)
    return sources, problems


def is_local_asset(url):
    parts = urlsplit(url)
    if parts.scheme or parts.netloc or url.startswith("//") or url.startswith("data:"):
        return False
    return parts.path.lower().endswith((".css", ".js"))


def with_version(url, version):
    parts = urlsplit(url)
    query = [q for q in parts.query.split("&") if q and not q.startswith("v=")]
    query.append("v=" + version)
    out = parts.path + "?" + "&".join(query)
    if parts.fragment:
        out += "#" + parts.fragment
    return out


def stamp_text(text, path, generated):
    """Return (new_text, stamped_refs, problems) for the page text that belongs at path."""
    page_dir = os.path.dirname(path)
    refs, problems = [], []

    def fix_tag(m):
        tag, attrs = m.group(1).lower(), m.group(2)
        want = "href" if tag == "link" else "src"

        def fix_attr(a):
            if a.group(1).lower() != want:
                return a.group(0)
            url = a.group(4)
            if not is_local_asset(url):
                return a.group(0)
            target = os.path.normpath(os.path.join(page_dir, urlsplit(url).path))
            if target in generated:
                data = generated[target]
            elif os.path.isfile(target):
                data = read_bytes(target)
            else:
                problems.append("%s: %s does not exist" % (os.path.relpath(path, PRIMER), url))
                return a.group(0)
            refs.append(os.path.relpath(target, PRIMER))
            return a.group(1) + a.group(2) + a.group(3) + with_version(url, short_hash(data)) + a.group(3)

        return "<" + m.group(1) + ATTR.sub(fix_attr, attrs) + ">"

    return TAG.sub(fix_tag, text), refs, problems


ALLOWED_CSS_HOSTS = ("https://fonts.googleapis.com/", "https://cdnjs.cloudflare.com/ajax/libs/KaTeX/")
STYLE_ELEMENT = re.compile(r"<style\b", re.I)
STYLESHEET_LINK = re.compile(r"<link\b[^>]*\brel\s*=\s*[\"']stylesheet[\"'][^>]*>", re.I)


def lint_page(path, text):
    """Problems with the rule 'no <style> element, no stylesheet except the library, KaTeX, fonts and the chapter's own css'."""
    problems = []
    rel = os.path.relpath(path, PRIMER)
    slug = os.path.basename(os.path.dirname(path))
    if STYLE_ELEMENT.search(re.sub(r"<script\b.*?</script>", "", text, flags=re.S | re.I)):
        problems.append("%s: has a <style> element (put the rules in %s.css or in lib/css)" % (rel, slug))
    for tag in STYLESHEET_LINK.findall(text):
        m = ATTR.search(tag)
        href = m.group(4) if m else ""
        path_only = urlsplit(href).path
        if href.startswith(ALLOWED_CSS_HOSTS) or path_only in ("../assets/kit.css", "assets/kit.css", slug + ".css"):
            continue
        problems.append("%s: stylesheet link %s is not the library, KaTeX, fonts or the chapter's own css" % (rel, href))
    return problems


def check_starter(chapters, libs, snippets):
    """The starter in lib/starter must stay a valid page. Render it as a chapter called 'starter' and lint it."""
    data, _ = chapters
    fake = {"starter": {"id": "x0", "num": "X0", "slug": "starter", "title": "Starter", "part": next(iter(data["parts"]))}}
    path = os.path.join(LIB, "starter", "index.html")
    try:
        text = pages.render_page(os.path.join(LIB, "starter", "page.html"), chapters=(data, fake), libs=libs, snippets=snippets)
    except pages.PageError as e:
        return [str(e)]
    return lint_page(path, text)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Build assets/kit.css and assets/kit.js, build every index.html from its page.html and stamp version hashes into the pages.")
    ap.add_argument("--check", action="store_true", help="write no files; exit 1 if something is stale")
    ap.add_argument("--snippets", action="store_true", help="list the snippets in lib/snippets and the pages that use each; write no files")
    args = ap.parse_args(argv)
    if args.snippets:
        args.check = True

    css_text, css_files = build_css()
    js_text = build_js()
    generated = {KIT_CSS_OUT: css_text.encode("utf-8"), KIT_JS_OUT: js_text.encode("utf-8")}

    stale, written, problems, stamp_counts = [], [], [], {}
    for out, new in ((KIT_CSS_OUT, generated[KIT_CSS_OUT]), (KIT_JS_OUT, generated[KIT_JS_OUT])):
        old = read_bytes(out) if os.path.isfile(out) else None
        if old != new:
            stale.append(os.path.relpath(out, PRIMER))
            if not args.check:
                os.makedirs(os.path.dirname(out), exist_ok=True)
                with open(out, "wb") as f:
                    f.write(new)
                written.append(os.path.relpath(out, PRIMER))

    sources, probs = page_sources()
    problems += probs
    chapters, libs = pages.load_chapters(), pages.load_libs()
    try:
        snippets = pages.load_snippets()
    except pages.PageError as e:
        print("PROBLEMS:\n  " + str(e))
        return 2
    used, expansions, users = set(), [], {}
    problems += pages.check_snippets(snippets)
    problems += check_starter(chapters, libs, snippets)
    touched = []
    for src in sources:
        path = os.path.join(os.path.dirname(src), "index.html")        # the generated page
        page_used = set()
        try:
            raw = pages.render_page(src, chapters=chapters, libs=libs, snippets=snippets, used=page_used)
        except pages.PageError as e:
            problems.append(str(e))
            continue
        used |= page_used
        expansions.append(len(page_used))
        for k in page_used:
            users.setdefault(k, []).append(os.path.basename(os.path.dirname(src)) or "index")
        new_text, refs, probs = stamp_text(raw, path, generated)
        problems += probs + lint_page(path, new_text)
        for r in refs:
            key = r if r.startswith("assets/") else ("chapter " + os.path.splitext(r)[1])
            stamp_counts[key] = stamp_counts.get(key, 0) + 1
        old_text = read_text(path) if os.path.isfile(path) else None
        if new_text != old_text:
            touched.append(os.path.relpath(path, PRIMER))
            stale.append(os.path.relpath(path, PRIMER))
            if not args.check:
                with open(path, "w", encoding="utf-8", newline="") as f:
                    f.write(new_text)

    if args.snippets:
        print("snippets in lib/snippets (a page counts when its text reaches the snippet, directly or through another snippet)")
        for key in sorted(snippets):
            pg = sorted(users.get(key, []))
            print("  %-26s %2d page%s  %s" % (key, len(pg), " " if len(pg) == 1 else "s", " ".join(pg) if len(pg) <= 8 else " ".join(pg[:8]) + " ..."))
        for p in problems:
            print("PROBLEM: " + p)
        return 2 if problems else 0
    print("primer library build%s" % (" (check only)" if args.check else ""))
    print("  css  : %d files from lib/css -> assets/kit.css  %s bytes  v=%s" % (len(css_files), format(len(generated[KIT_CSS_OUT]), ","), short_hash(generated[KIT_CSS_OUT])))
    print("  js   : lib/kit.js -> assets/kit.js  %s bytes  v=%s" % (format(len(generated[KIT_JS_OUT]), ","), short_hash(generated[KIT_JS_OUT])))
    print("  pages: %d built from page.html, %d %s" % (len(sources), len(touched), "stale" if args.check else "rewritten"))
    print("  stamps: " + ", ".join("%s x%d" % (k, v) for k, v in sorted(stamp_counts.items())))
    print("  snippets: %d in lib/snippets, %d used by %d pages" % (len(snippets), len(used & set(snippets)), sum(1 for n in expansions if n)))
    unused = sorted(set(snippets) - used)
    for key in unused:
        print("  WARNING: snippet %r is not used by any page (lib/snippets/%s.html). Use it or delete it" % (key, key))
    if written:
        print("  wrote: " + ", ".join(written[:6]) + (" ..." if len(written) > 6 else ""))
    if problems:
        print("PROBLEMS:")
        for p in problems:
            print("  " + p)
        return 2
    if args.check and stale:
        print("STALE (run python3 primer/lib/build.py): " + ", ".join(stale[:8]) + (" ... and %d more" % (len(stale) - 8) if len(stale) > 8 else ""))
        return 1
    print("  up to date" if not (written or touched) else "  done")
    return 0


if __name__ == "__main__":
    sys.exit(main())

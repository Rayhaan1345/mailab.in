#!/usr/bin/env python3
"""Build the primer library.

    python3 primer/lib/build.py            write what is stale
    python3 primer/lib/build.py --check    write no files, exit 1 if something is stale

What it does, in order:
  1. Joins lib/css/*.css (filename order) into assets/kit.css.
  2. Copies lib/kit.js to assets/kit.js.
  3. Stamps all local stylesheet and script references in the pages with ?v=<first 8 hex of the
     sha1 of that file's content>: assets/kit.css, assets/kit.js, the chapter's own <slug>.js and
     <slug>.css, and any other local .js or .css file beside a page. External URLs are left alone.

  4. Checks the rule "no <style> element in a page": a page may carry the library link, the chapter's own <slug>.css, the
     KaTeX and Google Fonts links, and nothing else that styles it. A <style> element or another stylesheet is a problem.

A second run finds nothing to change. Standard library only.
"""
import argparse
import glob
import hashlib
import os
import re
import sys
from urllib.parse import urlsplit

LIB = os.path.dirname(os.path.abspath(__file__))
PRIMER = os.path.dirname(LIB)
CSS_DIR = os.path.join(LIB, "css")
KIT_JS_SRC = os.path.join(LIB, "kit.js")
KIT_CSS_OUT = os.path.join(PRIMER, "assets", "kit.css")
KIT_JS_OUT = os.path.join(PRIMER, "assets", "kit.js")

CSS_HEADER = "/* Generated by lib/build.py from lib/css. Do not edit. */\n"
JS_HEADER = "// Generated by lib/build.py from lib/kit.js. Do not edit.\n"

TAG = re.compile(r"<(link|script)\b([^>]*)>", re.I)
ATTR = re.compile(r"""\b(href|src)(\s*=\s*)(["'])([^"']*)\3""", re.I)


def read_bytes(path):
    with open(path, "rb") as f:
        return f.read()


def read_text(path):
    return read_bytes(path).decode("utf-8")


def short_hash(data):
    return hashlib.sha1(data).hexdigest()[:8]


def build_css():
    files = sorted(glob.glob(os.path.join(CSS_DIR, "*.css")))
    if not files:
        raise SystemExit("no css files in " + CSS_DIR)
    parts = []
    for path in files:
        text = read_text(path)
        if not text.endswith("\n"):
            text += "\n"
        parts.append(text)
    return CSS_HEADER + "\n".join(parts), [os.path.basename(p) for p in files]


def build_js():
    text = read_text(KIT_JS_SRC)
    if not text.endswith("\n"):
        text += "\n"
    return JS_HEADER + text


def page_files():
    pages = sorted(glob.glob(os.path.join(PRIMER, "*", "index.html")))
    top = os.path.join(PRIMER, "index.html")
    if os.path.exists(top):
        pages.insert(0, top)
    # extra pages that live in the starter folder
    pages += sorted(p for p in glob.glob(os.path.join(PRIMER, "_template", "*.html"))
                    if os.path.basename(p) != "index.html")
    return pages


def is_local_asset(url):
    parts = urlsplit(url)
    if parts.scheme or parts.netloc or url.startswith("//") or url.startswith("data:"):
        return False
    return parts.path.lower().endswith((".css", ".js"))


def with_version(url, version):
    parts = urlsplit(url)
    query = [q for q in parts.query.split("&") if q and not q.startswith("v=")]
    query.append("v=" + version)
    out = parts.path + "?" + "&".join(query)
    if parts.fragment:
        out += "#" + parts.fragment
    return out


def stamp_page(path, generated):
    """Return (new_text, stamped_refs, problems) for one page."""
    text = read_text(path)
    page_dir = os.path.dirname(path)
    refs, problems = [], []

    def fix_tag(m):
        tag, attrs = m.group(1).lower(), m.group(2)
        want = "href" if tag == "link" else "src"

        def fix_attr(a):
            if a.group(1).lower() != want:
                return a.group(0)
            url = a.group(4)
            if not is_local_asset(url):
                return a.group(0)
            target = os.path.normpath(os.path.join(page_dir, urlsplit(url).path))
            if target in generated:
                data = generated[target]
            elif os.path.isfile(target):
                data = read_bytes(target)
            else:
                problems.append("%s: %s does not exist" % (os.path.relpath(path, PRIMER), url))
                return a.group(0)
            refs.append(os.path.relpath(target, PRIMER))
            return a.group(1) + a.group(2) + a.group(3) + with_version(url, short_hash(data)) + a.group(3)

        return "<" + m.group(1) + ATTR.sub(fix_attr, attrs) + ">"

    return TAG.sub(fix_tag, text), refs, problems


ALLOWED_CSS_HOSTS = ("https://fonts.googleapis.com/", "https://cdnjs.cloudflare.com/ajax/libs/KaTeX/")
STYLE_ELEMENT = re.compile(r"<style\b", re.I)
STYLESHEET_LINK = re.compile(r"<link\b[^>]*\brel\s*=\s*[\"']stylesheet[\"'][^>]*>", re.I)


def lint_page(path, text):
    """Problems with the rule 'no <style> element, no stylesheet except the library, KaTeX, fonts and the chapter's own css'."""
    problems = []
    rel = os.path.relpath(path, PRIMER)
    slug = os.path.basename(os.path.dirname(path))
    if STYLE_ELEMENT.search(re.sub(r"<script\b.*?</script>", "", text, flags=re.S | re.I)):
        problems.append("%s: has a <style> element (put the rules in %s.css or in lib/css)" % (rel, slug))
    for tag in STYLESHEET_LINK.findall(text):
        m = ATTR.search(tag)
        href = m.group(4) if m else ""
        path_only = urlsplit(href).path
        if href.startswith(ALLOWED_CSS_HOSTS) or path_only in ("../assets/kit.css", "assets/kit.css", slug + ".css"):
            continue
        problems.append("%s: stylesheet link %s is not the library, KaTeX, fonts or the chapter's own css" % (rel, href))
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description="Build assets/kit.css and assets/kit.js and stamp version hashes into pages.")
    ap.add_argument("--check", action="store_true", help="write no files; exit 1 if something is stale")
    args = ap.parse_args(argv)

    css_text, css_files = build_css()
    js_text = build_js()
    generated = {KIT_CSS_OUT: css_text.encode("utf-8"), KIT_JS_OUT: js_text.encode("utf-8")}

    stale, written, problems, stamp_counts = [], [], [], {}
    for out, new in ((KIT_CSS_OUT, generated[KIT_CSS_OUT]), (KIT_JS_OUT, generated[KIT_JS_OUT])):
        old = read_bytes(out) if os.path.isfile(out) else None
        if old != new:
            stale.append(os.path.relpath(out, PRIMER))
            if not args.check:
                os.makedirs(os.path.dirname(out), exist_ok=True)
                with open(out, "wb") as f:
                    f.write(new)
                written.append(os.path.relpath(out, PRIMER))

    pages = page_files()
    touched = []
    for path in pages:
        new_text, refs, probs = stamp_page(path, generated)
        problems += probs
        if "_template" not in path.split(os.sep): problems += lint_page(path, new_text)     # the starter folder is not published
        for r in refs:
            key = r if r.startswith("assets/") else ("chapter " + os.path.splitext(r)[1])
            stamp_counts[key] = stamp_counts.get(key, 0) + 1
        if new_text != read_text(path):
            touched.append(os.path.relpath(path, PRIMER))
            stale.append(os.path.relpath(path, PRIMER))
            if not args.check:
                with open(path, "w", encoding="utf-8", newline="") as f:
                    f.write(new_text)

    print("primer library build%s" % (" (check only)" if args.check else ""))
    print("  css  : %d files from lib/css -> assets/kit.css  %s bytes  v=%s" % (len(css_files), format(len(generated[KIT_CSS_OUT]), ","), short_hash(generated[KIT_CSS_OUT])))
    print("  js   : lib/kit.js -> assets/kit.js  %s bytes  v=%s" % (format(len(generated[KIT_JS_OUT]), ","), short_hash(generated[KIT_JS_OUT])))
    print("  pages: %d scanned, %d %s" % (len(pages), len(touched), "stale" if args.check else "rewritten"))
    print("  stamps: " + ", ".join("%s x%d" % (k, v) for k, v in sorted(stamp_counts.items())))
    if written:
        print("  wrote: " + ", ".join(written[:6]) + (" ..." if len(written) > 6 else ""))
    if problems:
        print("PROBLEMS:")
        for p in problems:
            print("  " + p)
        return 2
    if args.check and stale:
        print("STALE (run python3 primer/lib/build.py): " + ", ".join(stale[:8]) + (" ... and %d more" % (len(stale) - 8) if len(stale) > 8 else ""))
        return 1
    print("  up to date" if not (written or touched) else "  done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
